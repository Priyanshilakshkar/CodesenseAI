package com.codeSense_Ai.Reviews;

import com.codeSense_Ai.Dto.PostedReview;
import com.codeSense_Ai.Enties.Repositories;
import com.codeSense_Ai.model.CodeChunk;
import com.codeSense_Ai.model.DiffFile;
import com.codeSense_Ai.model.RepoReviewConfig;
import com.codeSense_Ai.model.ReviewIssue;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;

import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

@Service
@RequiredArgsConstructor
@Slf4j
public class ReviewPostingService {
    private final ReviewAggregator      aggregator;
    private final   DuplicateReviews   duplicateDetector;
    private final CommentLimitEnforcer  limitEnforcer;
    private final ReviewCommentPoster   commentPoster;
    private final ReviewSummaryPoster   summaryPoster;
    private final GithubReviewPoster    gitHubReviewPoster;

    public PostedReview post(Map<CodeChunk, List<ReviewIssue>> chunkResults,
                             List<DiffFile> diffFiles,
                             Repositories repository,
                             int               prNumber,
                             RepoReviewConfig config,
                             String            modelUsed,
                             int               totalTokens){
        Map<String, DiffFile> diffFilesByPath = diffFiles.stream()
                .collect(Collectors.toMap(DiffFile::getNewPath, f -> f));

        // ── Step 1: Aggregate ─────────────────────────────────────
        ReviewAggregator.AggregatedReview aggregated =
                aggregator.aggregate(chunkResults);

        if (aggregated.totalIssues() == 0) {
            // No issues — post a clean summary only
            return postCleanReview(repository, prNumber, modelUsed, totalTokens);
        }

        // ── Step 2: Deduplicate ───────────────────────────────────
        List<ReviewIssue> deduplicated = duplicateDetector.Duplicates(aggregated);
        int duplicatesRemoved = aggregated.totalIssues() - deduplicated.size();

        // ── Step 3: Enforce limit ─────────────────────────────────
        CommentLimitEnforcer.EnforcedResult enforced =
                limitEnforcer.enforce(deduplicated, config.getMaxComments());

        // ── Step 4: Map to diff positions ─────────────────────────
        ReviewCommentPoster.MappingResult mapped =
                commentPoster.buildComment(enforced.issues(), diffFilesByPath);

        // ── Step 5: Build summary body ────────────────────────────
        String summaryBody = summaryPoster.buildSummary(
                aggregated, enforced, mapped, modelUsed, totalTokens
        );

        // ── Step 6: POST to GitHub ────────────────────────────────
        long reviewId = gitHubReviewPoster.postReview(
                repository, prNumber, summaryBody, mapped.comments()
        );

        log.info("Review posting complete: reviewId={} posted={} dropped={} dupes={}",
                reviewId, mapped.mappedCount(),
                enforced.droppedCount(), duplicatesRemoved);

        return new PostedReview(
                reviewId,
                mapped.mappedCount(),
                enforced.droppedCount() + mapped.unmappedCount(),
                duplicatesRemoved,
                summaryBody
        );
    }

    private PostedReview postCleanReview(Repositories repository, int prNumber,
                                         String modelUsed, int totalTokens) {
        String cleanSummary = """
            ## 🤖 CodeSense AI Review

            ✅ **No issues found.** The changed code looks good!

            ---
            *Generated by CodeSense AI · Model: `%s` · Tokens used: %,d*
            """.formatted(modelUsed, totalTokens);

        long reviewId = gitHubReviewPoster.postReview(
                repository, prNumber, cleanSummary, List.of()
        );

        return new PostedReview(reviewId, 0, 0, 0, cleanSummary);
    }

}
